// ── Runtime state ──────────────────────────────────────────────

export let lang: LangTag = "en";

// ── Init ────────────────────────────────────────────────────────

/** Call once on startup, after Tauri IPC is ready. */
export async function initI18n(): Promise<void> {
  const detected = await invoke<string>("get_system_language").catch(() => "en");
  lang = detected || "en";
  document.documentElement.lang = lang;
}

// ── Translation function ────────────────────────────────────────

/**
 * Translate a key into the current language.
 * Supports "{param}" substitution: t("status.ai", { mode: "AGENT" })
 * Falls back to English if the key or language is missing.
 */
export function t(key: string, params?: Record<string, string>): string {
  const entry = DICT[key];
  if (!entry) return key;
  let text = entry[lang] ?? entry["en"] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, v);
    }
  }
  return text;
}

/** Type-safe plugin name translation by plugin ID. */
export function pluginName(id: string): string {
  return t(`plugin.${id}`);
}

/** Switch language at runtime (used by settings). Returns new tag. */
export function setLanguage(tag: LangTag): LangTag {
  if (DICT["search.placeholder"][tag]) {
    lang = tag;
    document.documentElement.lang = lang;
    localStorage.setItem("lunac_lang", tag);
  }
  return lang;
}

/** Restore persisted language preference (overrides system default). */
export function loadSavedLanguage(): void {
  const saved = localStorage.getItem("lunac_lang");
  if (saved && DICT["search.placeholder"][saved]) {
    lang = saved;
    document.documentElement.lang = lang;
  }
}

/** Revert to following the OS language (removes the persisted override). */
export async function resetToSystemLanguage(): Promise<void> {
  try {
    localStorage.removeItem("lunac_lang");
  } catch {}
  await initI18n();
}
